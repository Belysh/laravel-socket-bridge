/** Syntax checks plus real TLS Socket.IO traffic through the shipped reverse-proxy templates. */
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { chmod, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import http from 'node:http';
import https from 'node:https';
import { resolve } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { io } from '../gateway/node_modules/socket.io-client/build/esm-debug/index.js';

const root = resolve(import.meta.dirname, '..');
const reports = resolve(root, '.test-results');
await mkdir(reports, { recursive: true });
const temporary = await mkdtemp(resolve(reports, 'deploy-template-run-'));
const suffix = `${process.pid}-${randomBytes(4).toString('hex')}`;
const prefix = `socket-bridge-templates-${suffix}`;
const validatorImage = `${prefix}-validator`;
const containers = new Set();
const images = {
  nginx: 'nginx:1.29-alpine@sha256:5616878291a2eed594aee8db4dade5878cf7edcb475e59193904b198d9b830de',
  caddy: 'caddy:2-alpine@sha256:de23def33b17fb5d1290b0f6c2add1d70780e52341896c00a4c8a2a2fe9d355e',
  prometheus: 'prom/prometheus:latest@sha256:5ce7540c3c00ef4ab0c9d2c995c6a5b9c421f44b4a115d97a2c7af3b1c21cbb0',
  node: 'node:24-alpine@sha256:ebfe2f90462722a7a4de65e91990e97fe0d401c70e0e762c5b53302f905ec1c1',
  debian: 'debian:bookworm-slim@sha256:3783cc01769c7b2b1b83a5c5ad96c815348e28ed7da68e2e3687004faa906251',
};
let interrupted;
const interrupt = signal => { interrupted = signal; };
const onInt = () => interrupt('SIGINT');
const onTerm = () => interrupt('SIGTERM');
process.on('SIGINT', onInt); process.on('SIGTERM', onTerm);
function assertRunning() { if (interrupted) throw new Error(`Template validation interrupted (${interrupted}); cleaning up its own resources.`); }
const checks = [];
const report = { passed: false, images, checks };
function run(binary, args, input) {
  assertRunning();
  const result = spawnSync(binary, args, { cwd: root, encoding: 'utf8', timeout: 240_000, maxBuffer: 2 * 1024 * 1024, input });
  if (result.error || result.status !== 0) {
    throw new Error(`${binary} ${args.slice(0, 3).join(' ')} failed: ${result.error?.message ?? ''}\n${(`${result.stdout ?? ''}\n${result.stderr ?? ''}`).slice(-8_000)}`);
  }
  return result.stdout.trim();
}
function dockerRun(name, args) {
  containers.add(name);
  return run('docker', ['run', '--name', name, ...args]);
}
function removeContainer(name) {
  // The name is generated by this invocation; no application containers are selected.
  spawnSync('docker', ['rm', '-f', name], { encoding: 'utf8', timeout: 30_000 });
  containers.delete(name);
}
function passed(name) { assertRunning(); checks.push(name); console.log(`PASS ${name}`); }
const mount = (source, target) => ['-v', `${source}:${target}:ro`];
const templates = resolve(root, 'stubs/deploy');

try {
  run('docker', ['version', '--format', '{{.Server.Version}}']);
  run('openssl', ['req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-keyout', resolve(temporary, 'privkey.pem'),
    '-out', resolve(temporary, 'fullchain.pem'), '-days', '1', '-subj', '/CN=realtime.example.com',
    '-addext', 'subjectAltName=DNS:realtime.example.com', '-addext', 'basicConstraints=critical,CA:TRUE']);
  await chmod(resolve(temporary, 'privkey.pem'), 0o600);
  const caddy = await readFile(resolve(templates, 'Caddyfile'), 'utf8');
  // Test-only certificate injection; production keeps Caddy's automatic TLS default.
  await writeFile(resolve(temporary, 'Caddyfile'), caddy.replace('realtime.example.com {',
    'realtime.example.com {\n    tls /certs/fullchain.pem /certs/privkey.pem'));
  await writeFile(resolve(temporary, 'token'), randomBytes(32).toString('hex'));
  await writeFile(resolve(temporary, 'supervisor-wrapper.conf'), '[supervisord]\nlogfile=/tmp/bridge-supervisor.log\npidfile=/tmp/bridge-supervisor.pid\nchildlogdir=/tmp\n\n[include]\nfiles=/templates/supervisor.conf\n');
  await writeFile(resolve(temporary, 'backend.mjs'), `
import {createServer} from 'node:http';
import {createRequire} from 'node:module';
const require=createRequire('/work/gateway/package.json');
const {Server}=require('socket.io');
const http=createServer((_req,res)=>{res.writeHead(200);res.end('private backend');});
const io=new Server(http,{transports:['websocket']});
io.use((socket,next)=>socket.handshake.auth.token==='proxy-test'?next():next(new Error('Unauthorized')));
io.on('connection',socket=>socket.on('proxy.check',(payload,ack)=>ack({payload,proto:socket.handshake.headers['x-forwarded-proto'],origin:socket.handshake.headers.origin,host:socket.handshake.headers.host})));
http.listen(6001,'0.0.0.0',()=>console.log('backend ready'));
`);

  dockerRun(`${prefix}-nginx-check`, [...mount(resolve(templates, 'nginx.conf'), '/etc/nginx/conf.d/default.conf'),
    ...mount(temporary, '/etc/ssl/socket-bridge'), images.nginx, 'nginx', '-t']);
  passed('Nginx template syntax');
  dockerRun(`${prefix}-caddy-check`, [...mount(resolve(temporary, 'Caddyfile'), '/etc/caddy/Caddyfile'),
    ...mount(temporary, '/certs'), images.caddy, 'caddy', 'validate', '--config', '/etc/caddy/Caddyfile', '--adapter', 'caddyfile']);
  passed('Caddy template syntax');
  dockerRun(`${prefix}-prometheus-check`, ['--entrypoint', '/bin/promtool',
    ...mount(resolve(templates, 'prometheus.yml'), '/etc/prometheus/prometheus.yml'),
    ...mount(resolve(temporary, 'token'), '/etc/prometheus/secrets/socket-bridge-token'), images.prometheus, 'check', 'config', '/etc/prometheus/prometheus.yml']);
  passed('Prometheus scrape configuration syntax');

  console.log('Preparing isolated Supervisor/systemd validators…');
  run('docker', ['build', '-t', validatorImage, '-'], `FROM ${images.debian}\nRUN apt-get update && apt-get install -y --no-install-recommends supervisor systemd php-cli && rm -rf /var/lib/apt/lists/*\n`);
  dockerRun(`${prefix}-systemd-check`, ['--entrypoint', 'systemd-analyze', ...mount(templates, '/templates'), validatorImage,
    'verify', '--man=no', '/templates/socket-bridge-gateway.service', '/templates/socket-bridge-commands@.service', '/templates/socket-bridge-outbox@.service']);
  passed('All three systemd units');
  dockerRun(`${prefix}-supervisor-check`, ['--entrypoint', 'python3', ...mount(templates, '/templates'), ...mount(temporary, '/fixture'), validatorImage, '-c',
    'import os; from supervisor.options import ServerOptions; os.makedirs("/srv/app/current/storage/logs",exist_ok=True); o=ServerOptions(); o.realize(args=["-c","/fixture/supervisor-wrapper.conf"]); assert sorted(len(g.process_configs) for g in o.process_group_configs)==[1,2,2]']);
  passed('Supervisor gateway + two commands + two outbox process definitions');

  const backend = `${prefix}-backend`;
  dockerRun(backend, ['-d', '-p', '127.0.0.1::443', '-p', '127.0.0.1::80', ...mount(root, '/work'),
    ...mount(resolve(temporary, 'backend.mjs'), '/fixture/backend.mjs'), images.node, 'node', '/fixture/backend.mjs']);
  let backendReady = false;
  for (let attempt = 0; attempt < 100; attempt++) {
    if (run('docker', ['logs', backend]).includes('backend ready')) { backendReady = true; break; }
    if (run('docker', ['inspect', '--format', '{{.State.Running}}', backend]) !== 'true') break;
    await delay(100);
  }
  assert.ok(backendReady, 'Socket.IO test backend did not start');
  const securePort = Number(run('docker', ['port', backend, '443/tcp']).split(':').at(-1));
  const plainPort = Number(run('docker', ['port', backend, '80/tcp']).split(':').at(-1));
  assert.ok(securePort > 0 && plainPort > 0);
  const ca = await readFile(resolve(temporary, 'fullchain.pem'));
  const lookup = (_hostname, options, callback) => {
    if (typeof options === 'function') { callback = options; options = {}; }
    callback(null, options?.all ? [{ address: '127.0.0.1', family: 4 }] : '127.0.0.1', 4);
  };
  const request = (path, secure = true) => new Promise((resolveResponse, reject) => {
    const req = (secure ? https : http).get({ hostname: 'realtime.example.com', port: secure ? securePort : plainPort, path, ca, lookup, timeout: 3000 }, res => {
      res.resume(); res.on('end', () => resolveResponse({ status: res.statusCode, location: res.headers.location }));
    });
    req.on('error', reject); req.on('timeout', () => req.destroy(new Error('Proxy HTTP request timed out.')));
  });
  for (const proxy of ['nginx', 'caddy']) {
    const name = `${prefix}-${proxy}`;
    const configMounts = proxy === 'nginx'
      ? [...mount(resolve(templates, 'nginx.conf'), '/etc/nginx/conf.d/default.conf'), ...mount(temporary, '/etc/ssl/socket-bridge')]
      : [...mount(resolve(temporary, 'Caddyfile'), '/etc/caddy/Caddyfile'), ...mount(temporary, '/certs')];
    dockerRun(name, ['-d', '--network', `container:${backend}`, ...configMounts, images[proxy]]);
    try {
      let available = false;
      for (let attempt = 0; attempt < 60; attempt++) {
        try { await request('/'); available = true; break; } catch { await delay(100); }
      }
      assert.ok(available, `${proxy} did not start listening`);
      for (const path of ['/metrics', '/health/ready', '/']) assert.equal((await request(path)).status, 404);
      const redirect = await request('/socket.io/?EIO=4&transport=websocket', false);
      assert.ok([301, 308].includes(redirect.status)); assert.match(redirect.location, /^https:\/\/realtime\.example\.com/);
      const agent = new https.Agent({ ca, lookup });
      const socket = io(`https://realtime.example.com:${securePort}`, {
        transports: ['websocket'], auth: { token: 'proxy-test' }, ca, agent, rejectUnauthorized: true,
        extraHeaders: { Origin: 'https://app.example.com' }, reconnection: false, timeout: 5000,
      });
      try {
        await new Promise((resolveConnection, reject) => {
          socket.once('connect', resolveConnection);
          socket.once('connect_error', error => reject(new Error(error.description?.message ?? error.message)));
        });
        const payload = { id: 42, text: 'TLS websocket roundtrip' };
        const reply = await socket.timeout(3000).emitWithAck('proxy.check', payload);
        assert.deepEqual(reply.payload, payload); assert.equal(reply.proto, 'https'); assert.equal(reply.origin, 'https://app.example.com');
        assert.match(reply.host, /^realtime\.example\.com(?::\d+)?$/);
      } finally { socket.disconnect(); agent.destroy(); }
      passed(`${proxy}: trusted TLS, WebSocket upgrade, authenticated Socket.IO ACK, forwarded headers, redirect and private-route isolation`);
    } finally { removeContainer(name); }
  }
  assertRunning();
  report.passed = true;
} catch (error) {
  report.error = error.message;
  process.exitCode = 1;
  console.error(error.message);
  for (const name of containers) {
    if (!/-backend$|-nginx$|-caddy$/.test(name)) continue;
    const logs = spawnSync('docker', ['logs', '--tail', '10', name], { encoding: 'utf8', timeout: 10_000 });
    const message = `${logs.stdout ?? ''}\n${logs.stderr ?? ''}`.trim().slice(-2000);
    if (message) console.error(`${name}: ${message}`);
  }
} finally {
  for (const name of [...containers].reverse()) removeContainer(name);
  spawnSync('docker', ['image', 'rm', '-f', validatorImage], { encoding: 'utf8', timeout: 30_000 });
  await rm(temporary, { recursive: true, force: true });
  await writeFile(resolve(reports, 'deploy-templates.json'), `${JSON.stringify(report, null, 2)}\n`);
  process.off('SIGINT', onInt); process.off('SIGTERM', onTerm);
}
